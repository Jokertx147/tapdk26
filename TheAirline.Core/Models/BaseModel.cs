using System;
using System.Collections.Generic;
using System.Linq;
using System.Reflection;
using System.Runtime.Serialization;
using TheAirline.Infrastructure;

namespace TheAirline.Models
{
    [System.Serializable]
    public abstract class BaseModel : ISerializable
    {
        protected readonly int Version;

        protected BaseModel()
        {
        }

        protected BaseModel(SerializationInfo info, StreamingContext context)
        {
            Version = info.GetInt16("version");

            IEnumerable<FieldInfo> fields =
                GetType()
                    .GetFields(BindingFlags.Instance | BindingFlags.NonPublic | BindingFlags.Public)
                    .Where(p => p.GetCustomAttribute(typeof (Versioning)) != null);

            IList<PropertyInfo> props =
                new List<PropertyInfo>(
                    GetType()
                        .GetProperties(BindingFlags.Instance | BindingFlags.NonPublic | BindingFlags.Public)
                        .Where(p => p.GetCustomAttribute(typeof (Versioning)) != null));

            IEnumerable<MemberInfo> propsAndFields = props.Cast<MemberInfo>().Union(fields).ToList();

            foreach (SerializationEntry entry in info)
            {
                MemberInfo prop =
                    propsAndFields.FirstOrDefault(
                        p => ((Versioning) p.GetCustomAttribute(typeof (Versioning))).Name == entry.Name);

                if (prop != null)
                {
                    var fieldInfo = prop as FieldInfo;
                    if (fieldInfo != null)
                    {
                        fieldInfo.SetValue(this, entry.Value);
                    }

                    else
                    {
                        SetProperty((PropertyInfo) prop, entry.Value);
                    }
                }
            }

            IEnumerable<MemberInfo> notSetProps =
                propsAndFields.Where(p => ((Versioning) p.GetCustomAttribute(typeof (Versioning))).Version > Version);

            foreach (MemberInfo notSet in notSetProps)
            {
                var ver = (Versioning) notSet.GetCustomAttribute(typeof (Versioning));

                if (ver.AutoGenerated)
                {
                    var set = notSet as FieldInfo;
                    if (set != null)
                    {
                        set.SetValue(this, ver.DefaultValue);
                    }
                    else
                    {
                        SetProperty((PropertyInfo) notSet, ver.DefaultValue);
                    }
                }
            }
        }

        /// <summary>
        ///     Sets a property, also when it is a get-only auto property (the compiler backing field is written then).
        /// </summary>
        private void SetProperty(PropertyInfo property, object value)
        {
            if (property.GetSetMethod(true) != null)
            {
                property.SetValue(this, value);
                return;
            }

            FieldInfo backingField = null;
            for (Type t = GetType(); t != null && backingField == null; t = t.BaseType)
            {
                backingField = t.GetField("<" + property.Name + ">k__BackingField",
                                          BindingFlags.Instance | BindingFlags.NonPublic | BindingFlags.DeclaredOnly);
            }

            // never replace the default value (set by the field initialiser) with null
            if (backingField != null && value != null)
            {
                backingField.SetValue(this, value);
            }
        }

        /// <summary>Adds the "version" entry once; a subclass chain calls this at every level and the most derived value wins.</summary>
        protected static void AddVersion(SerializationInfo info, int version)
        {
            foreach (SerializationEntry entry in info)
            {
                if (entry.Name == "version")
                {
                    return;
                }
            }
            info.AddValue("version", version);
        }

        public virtual void GetObjectData(SerializationInfo info, StreamingContext context)
        {
            // classes that do not override GetObjectData still need a version for the reading constructor
            AddVersion(info, 1);

            Type myType = GetType();

            IEnumerable<FieldInfo> fields =
                myType.GetFields(BindingFlags.Instance | BindingFlags.NonPublic | BindingFlags.Public)
                      .Where(p => p.GetCustomAttribute(typeof (Versioning)) != null);

            IList<PropertyInfo> props =
                new List<PropertyInfo>(
                    myType.GetProperties(BindingFlags.Instance | BindingFlags.NonPublic | BindingFlags.Public)
                          .Where(p => p.GetCustomAttribute(typeof (Versioning)) != null));

            IEnumerable<MemberInfo> propsAndFields = props.Cast<MemberInfo>().Union(fields);

            foreach (MemberInfo member in propsAndFields)
            {
                var fieldInfo = member as FieldInfo;
                object propValue = fieldInfo != null ? fieldInfo.GetValue(this) : ((PropertyInfo) member).GetValue(this, null);

                var att = (Versioning) member.GetCustomAttribute(typeof (Versioning));

                info.AddValue(att.Name, propValue);
            }
        }
    }
}